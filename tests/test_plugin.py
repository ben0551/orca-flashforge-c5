"""End-to-end tests for the FlashForge C5 OrcaSlicer plugin.

Runs the real plugin file against a mock Creator 5 (tests/mock_printer.py) and a
stub `orca` module (tests/fake_orca.py), then drives the tab's message protocol
exactly as the page's JavaScript does. Assertions are made against what the
*printer* received, not against what the plugin thinks it sent.

    python3 tests/test_plugin.py
"""

import base64
import importlib.util
import io
import json
import os
import shutil
import sys
import tempfile
import time
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import fake_orca                                     # noqa: E402
from mock_printer import MockServer                   # noqa: E402

PLATE_GCODE = (b"; generated by OrcaSlicer\n"
               b"G1 X10 Y10 E0.5 F1800\n" * 4000)
SLICE_INFO = b"""<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header><header_item key="X-BBL-Client-Type" value="slicer"/></header>
  <plate>
    <metadata key="index" value="1"/>
    <filament id="1" type="PLA" color="#FF0000" used_m="4.2" used_g="12.5"/>
    <filament id="2" type="PLA" color="#0000FF" used_m="1.1" used_g="3.3"/>
  </plate>
</config>
"""

RESULTS = []


def check(name, condition, detail=""):
    RESULTS.append((name, bool(condition), detail))
    mark = "PASS" if condition else "FAIL"
    print(f"  [{mark}] {name}" + (f" — {detail}" if detail and not condition else ""))
    return bool(condition)


def build_3mf(path):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as bundle:
        bundle.writestr("Metadata/plate_1.gcode", PLATE_GCODE)
        bundle.writestr("Metadata/slice_info.config", SLICE_INFO)
        bundle.writestr("3D/3dmodel.model", "<model/>")
    return path


def load_plugin(workdir):
    """Copy the plugin into its own directory and import it under a stub `orca`."""
    source = os.path.join(ROOT, "flashforge-c5_any.py")
    target = os.path.join(workdir, "flashforge-c5_any.py")
    shutil.copy2(source, target)

    sys.modules["orca"] = fake_orca.make_module()
    spec = importlib.util.spec_from_file_location("ffc5_under_test", target)
    module = importlib.util.module_from_spec(spec)
    sys.modules["ffc5_under_test"] = module
    spec.loader.exec_module(module)
    return module


class Tab:
    """Stands in for the page: records what the plugin posts back."""

    def __init__(self, capability):
        self.capability = capability
        self.inbox = []
        capability.post_message = self.inbox.append

    def send(self, message):
        self.capability.on_message(message)

    def latest(self, kind):
        for message in reversed(self.inbox):
            if message.get("type") == kind:
                return message
        return None

    def clear(self):
        self.inbox.clear()

    def seen(self, kind):
        return any(m.get("type") == kind for m in self.inbox)


def wait_for_job(tab, timeout=25):
    deadline = time.time() + timeout
    while time.time() < deadline:
        tab.send({"type": "job_status"})
        job = tab.latest("job")
        if job and job.get("done"):
            return job
        time.sleep(0.1)
    return None


def main():
    workdir = tempfile.mkdtemp(prefix="ffc5-test-")
    try:
        plugin = load_plugin(workdir)

        with MockServer() as server:
            host, port = "127.0.0.1", server.port
            printer = server.printer

            with open(os.path.join(workdir, "settings.json"), "w") as fh:
                json.dump({"host": host, "port": port, "serial": "SN123",
                           "check_code": "CODE9", "leveling": True,
                           "poll_seconds": 3}, fh)

            # ---------------------------------------------------------------
            print("\nRegistration")
            package = fake_orca.make_module()
            sys.modules["orca"] = package
            # Re-run the package's registration against a fresh stub so we can
            # see exactly what the plugin declares.
            spec = importlib.util.spec_from_file_location(
                "ffc5_reg", os.path.join(workdir, "flashforge-c5_any.py"))
            reg = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(reg)
            package.plugin_class().register_capabilities()
            names = {c.__name__ for c in package.registered_capabilities}
            check("registers exactly the tab and the printer agent",
                  names == {"FlashForgePage", "FlashForgeAgent"},
                  str(sorted(names)))
            check("declares the printer URLs and the staging directory",
                  any(u.startswith("http://127.0.0.1") for u in
                      package.requested_permissions.get("network_http", [])),
                  str(package.requested_permissions))

            # ---------------------------------------------------------------
            print("\nConnection and status")
            page = plugin.FlashForgePage()
            tab = Tab(page)
            tab.send({"type": "hello"})
            check("hello returns the saved settings", tab.latest("cfg") is not None)
            state = tab.latest("state")
            check("hello returns live printer status",
                  state and state["status"]["name"] == "Creator 5 Pro",
                  str(state)[:180])
            check("four material slots are reported",
                  state and len(state["status"]["spools"]) == 4)
            check("the printer file list comes back",
                  tab.latest("files") is not None)

            check("the tab exposes its HTML", "<div id=\"wrap\">" in page.get_ui())
            check("the tab is named FlashForge C5", page.get_name() == "FlashForge C5")

            # Idle firmware pads the job block with uninitialised memory; the
            # normaliser must not pass that through.
            printer.set(status="unzipping", printLayer=1310730, printProgress=0.0,
                        coolingFanSpeed=917507, estimatedRightWeight=1.01e-39,
                        printDuration=786435)
            tab.send({"type": "status"})
            idle = tab.latest("state")["status"]
            check("idle job fields are zeroed, not passed through raw",
                  idle["progress"] == 0 and idle["elapsed_s"] == 0
                  and idle["layer"] == 0)
            # ...and while printing they are real.
            printer.set(status="printing", printProgress=0.42, printDuration=600,
                        estimatedTime=900, printLayer=88, targetPrintLayer=200,
                        printFileName="widget.gcode")
            tab.send({"type": "status"})
            live = tab.latest("state")["status"]
            check("a live job reports progress, layer and times",
                  live["progress"] == 42.0 and live["layer"] == 88
                  and live["elapsed_s"] == 600 and live["remaining_s"] == 900,
                  str(live))
            check("an active job is flagged active", live["active"] is True)
            printer.set(status="ready")

            # ---------------------------------------------------------------
            print("\nThe upload wire contract")
            # The tab no longer sends anything: OrcaSlicer's own Print button
            # does, through the printer agent, and that path uploads with this
            # same client method. So the wire contract is asserted here.
            bundle = build_3mf(os.path.join(workdir, "model.gcode.3mf"))
            client = plugin.RUNTIME.client()
            send_path, extracted = plugin.unwrap_for_printer(bundle, "model.gcode.3mf")
            check("the .gcode.3mf bundle was unwrapped to plain G-code",
                  bool(extracted) and os.path.basename(send_path) == "model.gcode"
                  and open(send_path, "rb").read() == PLATE_GCODE,
                  os.path.basename(send_path))
            client.upload(send_path, print_now=False, leveling=True)

            check("the printer received exactly one upload", len(printer.uploads) == 1,
                  f"got {len(printer.uploads)}")
            up = printer.uploads[0]
            check("credentials arrived as headers, not in the body",
                  up["headers"].get("serialNumber") == "SN123"
                  and up["headers"].get("checkCode") == "CODE9")
            check("fileSize header matches the bytes sent",
                  up["headers"].get("fileSize") == str(len(up["bytes"])))
            check("the upload part is named gcodeFile",
                  up["filename"] == "model.gcode", up["filename"] or "")
            check("the bytes sent are the extracted G-code, not the bundle",
                  up["bytes"] == PLATE_GCODE,
                  f"{len(up['bytes'])} bytes vs {len(PLATE_GCODE)} expected")
            check("upload used printNow=false (the print starts separately)",
                  str(up["headers"].get("printNow")).lower() == "false")
            check("bed levelling is requested on the upload",
                  str(up["headers"].get("levelingBeforePrint")).lower() == "true")

            client.start_print("model.gcode", leveling=True)
            check("the print was started for the extracted G-code",
                  len(printer.prints) == 1
                  and printer.prints[0]["fileName"] == "model.gcode",
                  str(printer.prints)[:200])

            # ---------------------------------------------------------------
            print("\nA plain .gcode")
            plain = os.path.join(workdir, "plain.gcode")
            with open(plain, "wb") as fh:
                fh.write(b"G1 X0 Y0 E1 F1200\n" * 10)
            client.upload(plain, print_now=False, leveling=True)
            check("a plain .gcode is uploaded unchanged, not unwrapped",
                  printer.uploads[-1]["bytes"] == open(plain, "rb").read()
                  and printer.uploads[-1]["filename"] == "plain.gcode",
                  printer.uploads[-1]["filename"])

            # ---------------------------------------------------------------
            print("\nPreviewing a stored file")
            thumb = client.thumbnail("model.gcode")
            check("the preview comes back as PNG bytes",
                  thumb[:4] == b"\x89PNG" and len(thumb) > 50, str(thumb[:8]))
            check("the preview was requested for the right file",
                  printer.thumbs and printer.thumbs[-1] == "model.gcode",
                  str(printer.thumbs))
            tab.clear()
            tab.send({"type": "preview", "filename": "model.gcode"})
            shown = tab.latest("preview")
            check("the tab is handed the preview as an inline image",
                  shown is not None
                  and shown["filename"] == "model.gcode"
                  and shown["image"].startswith("data:image/png;base64,"),
                  str(shown)[:120])
            check("the inline image is the same bytes the printer sent",
                  shown is not None
                  and base64.b64decode(shown["image"].split(",", 1)[1]) == thumb)
            tab.send({"type": "preview", "filename": "not-here.gcode"})
            check("a preview for a file the printer does not have is an error",
                  tab.latest("error") is not None
                  and "not-here.gcode" not in (tab.latest("error") or {}).get(
                      "message", "not-here.gcode"),
                  str(tab.latest("error"))[:160])

            # ---------------------------------------------------------------
            print("\nReprint from printer storage")
            printer.set(status="ready")
            tab.clear()
            tab.send({"type": "reprint", "filename": "model.gcode"})
            job = wait_for_job(tab)
            check("reprint succeeds", job is not None and not job.get("error"),
                  str(job))
            check("reprint reuses the file already on the printer",
                  len(printer.uploads) == 2 and len(printer.prints) == 2,
                  f"{len(printer.uploads)} uploads, {len(printer.prints)} prints")
            check("reprint rebuilds the mapping from gcodeListDetail",
                  (printer.prints[-1].get("materialMappings") or [{}])[0]
                  .get("slotId") == 1,
                  str(printer.prints[-1].get("materialMappings")))
            tab.clear()
            tab.send({"type": "reprint", "filename": "not-here.gcode"})
            job = wait_for_job(tab)
            check("reprinting a missing file fails with a clear message",
                  job is not None and job.get("error")
                  and "no longer on the printer" in job["error"], str(job))

            # ---------------------------------------------------------------
            print("\nJob control")
            printer.set(status="printing", lightStatus="close")
            printer.control_noop = True     # the firmware ACKs and ignores
            tab.clear()
            tab.send({"type": "control", "action": "pause"})
            log = tab.latest("log") or {}
            check("an ACKed-but-ignored command is reported as unconfirmed",
                  log.get("level") == "error"
                  and "still reports" in (log.get("message") or ""),
                  str(log)[:200])
            check("both /control payload shapes were tried",
                  len(printer.controls) >= 2
                  and "args" in (printer.controls[0].get("payload") or {})
                  and "args" not in (printer.controls[1].get("payload") or {}),
                  str(printer.controls)[:220])

            printer.control_noop = False
            printer.controls.clear()
            tab.clear()
            tab.send({"type": "control", "action": "pause"})
            log = tab.latest("log") or {}
            check("a command that takes effect is confirmed",
                  log.get("level") != "error" and "paused" in (log.get("message") or ""),
                  str(log)[:200])
            check("pause is sent as jobCtl_cmd/pause",
                  printer.controls[0]["payload"]["cmd"] == "jobCtl_cmd"
                  and printer.controls[0]["payload"]["args"]["action"] == "pause",
                  str(printer.controls[0]))

            printer.set(status="paused", lightStatus="close")
            printer.controls.clear()
            tab.clear()
            tab.send({"type": "control", "action": "light", "on": True})
            check("light control is confirmed against lightStatus",
                  printer.state["lightStatus"] == "open"
                  and any(c["payload"]["cmd"] == "lightControl_cmd"
                          for c in printer.controls),
                  str(printer.controls)[:200])

            # ---------------------------------------------------------------
            print("\nPrinter agent")
            agent = plugin.FlashForgeAgent()
            info = agent.get_agent_info()
            check("the agent registers a unique id", info.id == "flashforge_c5")
            check("the agent reports as a printer-connection capability",
                  agent.get_type() == fake_orca.PluginType.PrinterConnection)
            params = fake_orca.PrinterConnectionParams(
                dev_id=host, host=host, port=str(port), password="CODE9")
            check("connect_printer succeeds against a reachable, authorised printer",
                  agent.connect_printer(params) == 0)
            bad = fake_orca.PrinterConnectionParams(
                dev_id="127.0.0.1", host="127.0.0.1", port=str(port),
                password="WRONG")
            check("connect_printer fails on a bad access code",
                  agent.connect_printer(bad) == -1)
            check("the agent exposes a camera URL",
                  agent.get_camera_url().endswith(":8080/?action=stream"))
            check("the agent pulls filament info rather than subscribing",
                  agent.get_filament_sync_mode()
                  == fake_orca.FilamentSyncMode.Pull)

            agent.connect_printer(params)
            printer.set(status="ready")
            before = len(printer.uploads)
            job_params = fake_orca.PrintParams(filename=bundle, dev_id=host)
            check("start_local_print uploads and starts the job",
                  agent.start_local_print(job_params, lambda *a: None,
                                          lambda: False) == 0
                  and len(printer.uploads) == before + 1
                  and printer.prints[-1]["fileName"] == "model.gcode")

            calls = []
            agent.start_send_gcode_to_sdcard(
                fake_orca.PrintParams(filename=bundle, project_name="verify_job"),
                lambda *a: None, lambda: False, lambda *a: False)
            check("the verify_job probe checks credentials without uploading",
                  len(printer.uploads) == before + 1, str(len(printer.uploads)))

            sent = []
            agent.set_on_ssdp_msg_fn(sent.append)
            agent.start_discovery(True, False)
            check("discovery emits an SSDP message for the configured printer",
                  sent and json.loads(sent[0])["dev_ip"] == host, str(sent)[:160])

            code = agent.send_message_to_printer(
                host, json.dumps({"print": {"command": "pause"}}), 0, False)
            check("a Bambu-style pause command is translated to /control",
                  code == 0 and printer.controls[-1]["payload"]["cmd"] == "jobCtl_cmd")
            check("a cloud-only command is refused rather than silently dropped",
                  agent.send_message(host, "{}", 0, False) == -7010)

            # ---------------------------------------------------------------
            print("\nOffline behaviour")
            printer_down = plugin.Runtime()
            saved = plugin.load_settings()
            plugin._SETTINGS_CACHE = dict(saved, host="127.0.0.1", port=9)
            started = time.time()
            status, error = printer_down.refresh()
            elapsed = time.time() - started
            check("an unreachable printer fails fast instead of hanging the UI",
                  status is None and error and elapsed < 2.0, f"{elapsed:.2f}s")
            # An unconfigured tab has to say so in a way the page can act on.
            # The state carries the flag, and the plain log line is suppressed
            # so it cannot overwrite the banner that offers the button.
            unset_tab = Tab(page)
            plugin._SETTINGS_CACHE = dict(saved, host="", serial="", check_code="")
            unset_tab.send({"type": "status"})
            state_msg = unset_tab.latest("state")
            check("an unconfigured tab flags itself for setup",
                  state_msg is not None and state_msg.get("needs_setup") is True,
                  str(state_msg)[:180])
            check("the setup flag suppresses the plain error log",
                  unset_tab.latest("log") is None,
                  str(unset_tab.latest("log"))[:180])
            _, setup_error = plugin.Runtime().refresh()
            check("the error text points at the panel, not a 'Settings' that does not exist",
                  "Printer connection" in (setup_error or "")
                  and "Settings" not in (setup_error or ""),
                  str(setup_error))

            configured_tab = Tab(page)
            plugin._SETTINGS_CACHE = dict(saved, host="127.0.0.1")
            configured_tab.send({"type": "status"})
            check("a configured tab does not flag setup",
                  configured_tab.latest("state").get("needs_setup") is False)

            # ---------------------------------------------------------------
            print("\nHelpers")
            check("colour names are human-readable",
                  plugin.color_name("#FFFFFF") == "White"
                  and plugin.color_name("#D01012") == "Red"
                  and plugin.color_name("nonsense") == "")
            # RGB distance would call these the wrong thing; hue gets them right.
            expected = {
                "#0057B8": "Sky blue", "#0000FF": "Blue", "#1A1AE6": "Blue",
                "#000000": "Black", "#E8E8E8": "White", "#7F7F7F": "Light grey",
                "#404040": "Grey", "#00A651": "Green", "#FFD700": "Gold",
                "#8B4513": "Brown", "#FF69B4": "Pink", "#8000FF": "Purple",
                "#00C0C0": "Teal", "#FFFF00": "Yellow", "#FF7F00": "Orange",
            }
            wrong = {c: (plugin.color_name(c), want) for c, want in expected.items()
                     if plugin.color_name(c) != want}
            check("the palette names colours the way people do", not wrong, str(wrong))
            check("an empty colour names nothing",
                  plugin.color_name("") == "" and plugin.color_name(None) == "")
            check("the light-state parser accepts the firmware's spellings",
                  plugin.normalize_detail({"lightStatus": "open"})["light_on"] is True
                  and plugin.normalize_detail({"lightStatus": "close"})["light_on"] is False)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
        staging = os.path.join(tempfile.gettempdir(), "ffc5-staging")
        shutil.rmtree(staging, ignore_errors=True)

    failed = [name for name, ok, _ in RESULTS if not ok]
    print(f"\n{len(RESULTS) - len(failed)}/{len(RESULTS)} checks passed")
    if failed:
        print("FAILED:")
        for name in failed:
            print("  -", name)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
